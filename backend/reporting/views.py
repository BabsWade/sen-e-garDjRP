from rest_framework import viewsets
from .models import AuditLog, ExportedData, Report
from .serializers import AuditLogSerializer, ReportSerializer, ExportedDataSerializer
import csv
from django.http import HttpResponse
from .models import Report
from rest_framework.permissions import IsAuthenticated  # ➕ à ajouter


class AuditLogViewSet(viewsets.ModelViewSet):
    queryset = AuditLog.objects.all()
    serializer_class = AuditLogSerializer
    permission_classes = [IsAuthenticated]


class ReportViewSet(viewsets.ModelViewSet):
    queryset = Report.objects.all()
    serializer_class = ReportSerializer
    permission_classes = [IsAuthenticated]


class ExportedDataViewSet(viewsets.ModelViewSet):
    queryset = ExportedData.objects.all()
    serializer_class = ExportedDataSerializer
    permission_classes = [IsAuthenticated]


def export_report(request):
    # Récupérer tous les rapports
    reports = Report.objects.all()

    # Créer une réponse HTTP avec le contenu CSV
    response = HttpResponse(content_type='text/csv')
    response['Content-Disposition'] = 'attachment; filename="report.csv"'

    # Créer un écrivain CSV
    writer = csv.writer(response)

    # Ajouter l'entête du CSV
    writer.writerow(['Report Type', 'Generated By', 'Generated At'])

    # Ajouter les données des rapports
    for report in reports:
        writer.writerow([report.report_type, report.generated_by, report.generated_at])

    return response